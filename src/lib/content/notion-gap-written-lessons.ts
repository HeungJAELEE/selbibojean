function block(
  lessonId: string,
  kind: LessonBlockKind,
  title: string,
  body: string,
  order: number,
): LessonBlock {
  return { id: `${lessonId}-${kind}-${order}`, kind, title, body, order };
}

function makeLesson(seed: GapLessonSeed): Lesson {
  const id = `notion-gap-${seed.slug}`;
  const substantiveCharacters = [
    ...seed.summary,
    seed.definition,
    seed.background,
    seed.comparison,
    seed.examPoint,
    seed.trap,
  ].join("").length;

  return {
    id,
    subjectId: seed.subjectId,
    conceptGroupId: seed.conceptGroupId,
    conceptId: `notion-gap-concept-${seed.slug}`,
    title: seed.title,
    aliases: seed.aliases,
    summary: seed.summary,
    blocks: [
      block(id, "definition", "정의", seed.definition, 1),
      block(id, "principle", seed.backgroundTitle, seed.background, 2),
      block(id, "selection", "특징과 비교", seed.comparison, 3),
      block(id, "exam_point", "시험에 자주 나오는 유형", seed.examPoint, 4),
      block(id, "trap", "대표 오답과 틀린 이유", seed.trap, 5),
      block(
        id,
        "source",
        "출처와 검토 범위",
        `- 편집 근거: ${seed.sourceUrl}\n- 비공개 편집 근거의 URL과 전문은 공개하지 않으며, 검토된 기출 표현과 구조만 학습용으로 재정리했습니다.\n- 최근 검토일: 2026-07-29`,
        6,
      ),
    ],
    relatedQuestionIds: [],
    coverageStatus: "covered",
    contentStatus: "published",
    sourceNeeded: false,
    reviewedAt: REVIEWED_AT,
    publication: { readiness: "ready", blockers: [] },
    quality: {
      tier: "standard",
      substantiveCharacters,
      genericPhraseMatches: [],
      languageIssueMatches: [],
      sourceLinked: true,
      passed: true,
    },
    contentRole: "supplemental",
  };
}

export const notionGapWrittenLessons = seeds.map(makeLesson);
