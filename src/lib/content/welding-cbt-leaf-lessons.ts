function buildLesson(spec: LeafLessonSpec): Lesson {
  const target = WELDING_CBT_LEAF_TARGETS[spec.id];
  const blocks = buildBlocks(spec);
  const substantiveCharacters = blocks
    .map((block) => `${block.title}${block.body}`.replace(/\s+/gu, ""))
    .join("").length;

  return {
    id: spec.id,
    subjectId: SUBJECT_ID,
    conceptGroupId: target.groupId,
    conceptId: `concept-${spec.id.replace(/^lesson-/u, "")}`,
    title: target.title,
    aliases: spec.aliases,
    summary: spec.summary,
    blocks,
    relatedQuestionIds: [],
    coverageStatus: "covered",
    contentStatus: "published",
    sourceNeeded: false,
    reviewedAt: REVIEWED_AT,
    contentRole: "exam_linked",
    publication: { readiness: "ready", blockers: [] },
    quality: {
      tier: "core",
      substantiveCharacters,
      genericPhraseMatches: [],
      languageIssueMatches: [],
      sourceLinked: true,
      passed: substantiveCharacters >= 900,
    },
  };
}

export const weldingCbtLeafLessons = NEW_LEAF_SPECS.map(buildLesson);
