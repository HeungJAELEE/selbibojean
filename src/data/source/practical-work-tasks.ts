export const PRACTICAL_WORK_MODULES: PracticalWorkModule[] = Object.entries(
  NCS_SOURCE_REGISTRY,
).map(([ncsCode, source]) => {
  const tasks = PRACTICAL_WORK_TASKS.filter((item) => item.ncsCode === ncsCode);
  return {
    ncsCode,
    documentTitle: source.title,
    version: source.version,
    sourceUrl: source.sourceUrl,
    description: moduleDescription(ncsCode),
    taskIds: tasks.map((item) => item.id),
    conceptIds: [...new Set(tasks.flatMap((item) => item.conceptIds))],
  };
});

export function getPracticalWorkTask(taskIdOrSlug: string) {
  return (
    taskById.get(taskIdOrSlug) ??
    PRACTICAL_WORK_TASKS.find((item) => item.slug === taskIdOrSlug)
  );
}

export function getPracticalWorkModule(ncsCode: string) {
  return PRACTICAL_WORK_MODULES.find((item) => item.ncsCode === ncsCode);
}

export function getPracticalWorkTasksForConcept(conceptId: string) {
  return PRACTICAL_WORK_TASKS.filter((item) =>
    item.conceptIds.includes(conceptId),
  );
}

