type StepInput = [
  phase: PracticalTaskPhase,
  title: string,
  instruction: string,
  completionEvidence: string,
  warning?: string,
];

type TaskInput = {
  id: string;
  slug: string;
  ncsCode: keyof typeof NCS_SOURCE_REGISTRY;
  title: string;
  summary: string;
  difficulty?: PracticalTaskContent["difficulty"];
  estimatedMinutes: number;
  conceptIds: string[];
  learningObjectives: string[];
  theoryTopics: string[];
  prerequisites: string[];
  tools: string[];
  materials?: string[];
  protectiveEquipment: string[];
  safety: Array<[label: string, guidance: string, allowNotApplicable?: boolean]>;
  steps: StepInput[];
  measurements: PracticalTaskMeasurement[];
  acceptanceChecks: string[];
  diagnostics: PracticalTaskDiagnostic[];
  recordFields?: PracticalTaskRecordField[];
  reviewNotes?: string[];
};

function task(input: TaskInput): PracticalTaskContent {
  const source = NCS_SOURCE_REGISTRY[input.ncsCode];
  const safetyChecks: PracticalTaskSafetyCheck[] = input.safety.map(
    ([label, guidance, allowNotApplicable], index) => ({
      id: `${input.id}-SAFE-${String(index + 1).padStart(2, "0")}`,
      label,
      guidance,
      allowNotApplicable: allowNotApplicable ?? false,
    }),
  );
  const steps: PracticalTaskStep[] = input.steps.map(
    ([phase, title, instruction, completionEvidence, warning], index) => ({
      id: `${input.id}-STEP-${String(index + 1).padStart(2, "0")}`,
      phase,
      title,
      instruction,
      completionEvidence,
      warning: warning ?? null,
    }),
  );

  return {
    id: input.id,
    slug: input.slug,
    version: 1,
    effectiveFrom: "2026-07-26",
    supersedesVersion: null,
    acceptanceRuleVersion: 1,
    safetyGateVersion: 1,
    safetyGateIds: safetyChecks.map((item) => item.id),
    publishBlockerIds: [],
    ncsCode: input.ncsCode,
    documentTitle: source.title,
    title: input.title,
    summary: input.summary,
    difficulty: input.difficulty ?? "intermediate",
    estimatedMinutes: input.estimatedMinutes,
    conceptIds: input.conceptIds,
    learningObjectives: input.learningObjectives,
    theoryTopics: input.theoryTopics,
    prerequisites: input.prerequisites,
    tools: input.tools,
    materials: input.materials ?? [],
    protectiveEquipment: input.protectiveEquipment,
    safetyChecks,
    steps,
    measurements: input.measurements,
    acceptanceChecks: input.acceptanceChecks,
    diagnostics: input.diagnostics,
    recordFields: input.recordFields ?? COMMON_RECORD_FIELDS,
    sourceRefs: [
      `${source.title} (${input.ncsCode}_${source.version})`,
      source.sourceUrl,
      ...input.conceptIds.map((conceptId) => `concept:${conceptId}`),
    ],
    reviewNotes: input.reviewNotes ?? [
      "수치·허용값·체결토크는 문제 조건과 해당 장비의 최신 제작사 매뉴얼·WPS·검사기준서를 우선한다.",
    ],
  };
}

function manualMeasurement(
  id: string,
  label: string,
  instrument: string,
  method: string,
  acceptanceCriteria: string,
  sourceCondition: string,
  unit: string | null = null,
): PracticalTaskMeasurement {
  return {
    id,
    label,
    valueType: unit ? "number" : "text",
    judgmentMode: "manual",
    formula: null,
    calculationRuleId: null,
    calculationRuleVersion: null,
    canonicalUnit: unit,
    acceptedInputUnits: unit ? [unit] : [],
    unitConversionGroup: unit ? `manual-${unit}` : null,
    displayPrecision: unit ? 3 : null,
    instrument,
    method,
    acceptanceCriteria,
    sourceCondition,
    allowedValues: [],
  };
}

