export function visualAidIdsForQuestion(
  questionId: string,
  directVisualAidIds: Array<string | null | undefined> = [],
) {
  const coverageVisualAidIds = PRACTICAL_VISUAL_COVERAGE.filter(
    (item) =>
      item.status === "ready" && item.questionIds.includes(questionId),
  ).flatMap((item) => item.visualAidIds);

  return [
    ...new Set(
      [...directVisualAidIds, ...coverageVisualAidIds].filter(
        (visualAidId): visualAidId is string => Boolean(visualAidId),
      ),
    ),
  ];
}

