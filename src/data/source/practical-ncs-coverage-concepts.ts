import type {
  PracticalConcept,
  PracticalSourceRef,
} from "@/lib/domain/practical-types";
import { NCS_SOURCE_REGISTRY } from "./practical-source-registry";

type CoverageConceptInput = {
  id: string;
  title: string;
  subjectLabel: PracticalConcept["subjectLabel"];
  groupLabel: PracticalConcept["groupLabel"];
  learningGoals: string[];
  definition: string;
  principle: string;
  components?: string[];
  procedure?: string[];
  formula?: string[];
  diagnosis?: string[];
  safety?: string[];
  examFormats?: string[];
  requiredKeywords?: string[];
  traps?: string[];
  ncsSources: PracticalSourceRef[];
  ncsLearningPoints: string[];
  sourceReviewNote: string;
};

type NcsCode = keyof typeof NCS_SOURCE_REGISTRY;

function ncs(
  ncsCode: NcsCode,
  pdfPage: number,
  printedPage: number,
  performanceCriteria: string,
  figureNumber: string | null = null,
): PracticalSourceRef {
  const source = NCS_SOURCE_REGISTRY[ncsCode];
  return {
    ncsCode,
    documentTitle: source.title,
    version: source.version,
    pdfPage,
    printedPage,
    figureNumber,
    performanceCriteria,
    sourceFileHash: source.hash,
    sourceUrl: source.sourceUrl,
  };
}

function coverage(input: CoverageConceptInput): PracticalConcept {
  return {
    contentRole: "supplemental",
    labels: [],
    components: [],
    procedure: [],
    formula: [],
    diagnosis: [],
    safety: [],
    examFormats: [],
    requiredKeywords: [],
    traps: [],
    relatedPastQuestionIds: [],
    relatedPredictedQuestionIds: [],
    existingLessonId: null,
    theoryTreatment: "NCS 원문 기반 실기 보강 레슨 (+보강용)",
    visualAidIds: [],
    contentStatus: "published",
    ...input,
  };
}

