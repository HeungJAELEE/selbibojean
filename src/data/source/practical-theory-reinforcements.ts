function unique(values: string[]) {
  return [...new Set(values)];
}

export function applyPracticalTheoryReinforcement(
  concept: PracticalConcept,
): PracticalConcept {
  const reinforcement = REINFORCEMENTS[concept.id];
  if (!reinforcement) return concept;
  return {
    ...concept,
    learningGoals: unique([...concept.learningGoals, ...reinforcement.learningGoals]),
    principle: `${concept.principle}\n\n${reinforcement.principle.join(" ")}`,
    components: unique([...concept.components, ...reinforcement.components]),
    procedure: unique([...concept.procedure, ...reinforcement.procedure]),
    diagnosis: unique([...concept.diagnosis, ...reinforcement.diagnosis]),
    safety: unique([...concept.safety, ...reinforcement.safety]),
    examFormats: unique([...concept.examFormats, ...reinforcement.examFormats]),
    requiredKeywords: unique([...concept.requiredKeywords, ...reinforcement.requiredKeywords]),
    traps: unique([...concept.traps, ...reinforcement.traps]),
    ncsLearningPoints: unique([...concept.ncsLearningPoints, ...reinforcement.ncsLearningPoints]),
    sourceReviewNote: `${concept.sourceReviewNote} ${reinforcement.sourceReviewNote}`.trim(),
  };
}
